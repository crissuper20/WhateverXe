# gen-dither.py <420v|2vuy> <out.asm>: our own Gen12 (Xe-LP, IGA -p=12p1) kernels for AVD
# post-processing kernels 3 (420v output) and 2 (2vuy output), both with luma dither.
# Written from the observed behaviour of Apple's AVD kernels, not from Apple's code. Straight line:
# no loops, branches or math. One source for both, as the two kernels share all input work.
#
# Conservative software scoreboard, chosen for safety over speed:
#  - every in-order instruction carries {@1}: it waits for the previous one to finish, so
#    everything before it has finished, whatever the pipe latencies are;
#  - every send has its own SBID token, never reused; one sync.allwr after all reads and
#    one sync.allrd before EOT; headers are never rewritten after a send.
# Every instruction is (W) NoMask, so results do not depend on the media dispatch mask.
# Each GRF byte is written once before it is read (no write-after-write in headers).
#
# Payload: r0 = thread header, r1 = MEDIA_OBJECT inline data
#   r1.0 x, r1.1 y (top-left luma pixel of a 32x16 block), r1.2 k, r1.3 s,
#   r1.4 seed A (left 16 columns), r1.5 seed B (right 16 columns)
# Surfaces: 0 = source Y, 1 = source UV (interleaved, half height), 4 = 64x64 signed dither
#   420v: 2 = dest Y, 3 = dest UV;  2vuy: 2 = dest packed Cb Y0 Cr Y1, 2 bytes per pixel
# Luma:  Y'[r][c] = sat_u8(Y[r][c] + (int16)((D[r][c] * k) >> s))
#   D[r][c] = dither[oy + r][ox + c % 16], (ox, oy) = (seed & 48, (seed >> 16) & 48),
#   seed A for c < 16, seed B for c >= 16
# Chroma: 420v copies UV; 2vuy row r takes UV row r / 2 (no filter): out[2c] = UV[r/2][c],
#   out[2c + 1] = Y'[r][c], written at byte x * 2.
#
# Registers: r2-r6 read headers, r7 scalars, r8-r11 2vuy write headers, r12-r27 Y rows,
#   r28-r35 UV rows, r36-r43 dither A (2 rows per GRF), r44-r51 dither B, r52-r83 output,
#   r90-r121 temporaries (4 sets of 8), r127 copy of r0 for EOT.
import sys

mode, out = sys.argv[1], sys.argv[2]
assert mode in ('420v', '2vuy')
READ, WRITE = 0x02890000, 0x020A8000  # media block read rlen 8 / write mlen 1, header on
Y, UV, A, B, OUT, TMP = 12, 28, 36, 44, 52, 90
lines = []


def emit(text, note='', swsb='@1'):
    if swsb and len(lines) > 1:  # the first instruction has nothing to wait for
        text = '%-84s {%s}' % (text, swsb)
    lines.append('%-96s // %s' % (text, note) if note else text)


def header(reg, x, y, size, note):
    emit('(W)     mov (1|M0)               r%d.0<1>:d    %s' % (reg, x), note)
    emit('(W)     mov (1|M0)               r%d.1<1>:d    %s' % (reg, y))
    emit('(W)     mov (1|M0)               r%d.2<1>:ud   %s:ud' % (reg, size), 'block (h-1)<<16 | (w-1)')
    emit('(W)     mov (1|M0)               r%d.3<1>:ud   r0.3<0;1,0>:ud' % reg, 'rest of the header from r0')
    emit('(W)     mov (4|M0)               r%d.4<1>:ud   r0.4<4;4,1>:ud' % reg)


def send(dst, hdr, payload, desc, token, note):
    if payload is None:
        emit('(W)     send.dc1 (8|M0)          r%d      r%d      null    0x0    0x%08X' % (dst, hdr, desc), note, '@1,$%d' % token)
    else:
        emit('(W)     send.dc1 (8|M0)          null     r%d      r%d     0x200  0x%08X' % (hdr, payload, desc), note, '@1,$%d' % token)


lines.append('// AVD %s dither kernel for Gen12. Generated by gen-dither.py; edit that instead.' % mode)
emit('(W)     mov (8|M0)               r127.0<1>:ud  r0.0<8;8,1>:ud', 'keep r0 for EOT (must be r112-r127)')
emit('(W)     add (1|M0)               r7.0<1>:d     r1.1<0;1,0>:d     8:w', 'y + 8')
emit('(W)     shr (1|M0)               r7.1<1>:ud    r1.1<0;1,0>:ud    1:ud', 'y / 2 (y >= 0)')
emit('(W)     shr (2|M0)               r7.2<1>:ud    r1.4<1;1,0>:ud    16:ud', 'r7.2, r7.3 = seed A, B >> 16')
emit('(W)     and (2|M0)               r7.4<1>:d     r1.4<1;1,0>:d     48:w', 'r7.4, r7.5 = ox of A, B in 0..48')
emit('(W)     and (2|M0)               r7.2<1>:d     r7.2<1;1,0>:d     48:w', 'r7.2, r7.3 = oy of A, B in 0..48')
header(2, 'r1.0<0;1,0>:d', 'r1.1<0;1,0>:d', '0x7001F', 'Y rows 0-7, 32x8')
header(3, 'r1.0<0;1,0>:d', 'r7.0<0;1,0>:d', '0x7001F', 'Y rows 8-15, 32x8')
header(4, 'r1.0<0;1,0>:d', 'r7.1<0;1,0>:d', '0x7001F', 'UV rows 0-7, 32x8')
header(5, 'r7.4<0;1,0>:d', 'r7.2<0;1,0>:d', '0xF000F', 'dither A, 16x16')
header(6, 'r7.5<0;1,0>:d', 'r7.3<0;1,0>:d', '0xF000F', 'dither B, 16x16')
send(Y, 2, None, READ | 0, 0, 'Y rows 0-7 -> r%d-r%d' % (Y, Y + 7))
send(Y + 8, 3, None, READ | 0, 1, 'Y rows 8-15 -> r%d-r%d' % (Y + 8, Y + 15))
send(UV, 4, None, READ | 1, 2, 'UV rows 0-7 -> r%d-r%d' % (UV, UV + 7))
send(A, 5, None, READ | 4, 3, 'A -> r%d-r%d' % (A, A + 7))
send(B, 6, None, READ | 4, 4, 'B -> r%d-r%d' % (B, B + 7))
emit('        sync.allwr (1|M0)                null', 'wait for every read', None)

for row in range(16):
    t = TMP + 8 * (row % 4)
    ta, tb, pa, pb, s = t, t + 1, t + 2, t + 4, t + 6  # sum: s = columns 0-15, s+1 = 16-31
    d = '.%d' % (16 * (row % 2))
    emit('(W)     mov (16|M0)              r%d.0<1>:w    r%d%s<16;16,1>:b' % (ta, A + row // 2, d), 'row %d: D left' % row)
    emit('(W)     mov (16|M0)              r%d.0<1>:w    r%d%s<16;16,1>:b' % (tb, B + row // 2, d), 'D right')
    emit('(W)     mul (16|M0)              r%d.0<1>:d    r1.2<0;1,0>:d     r%d.0<16;16,1>:w' % (pa, ta), 'D * k, 32-bit')
    emit('(W)     mul (16|M0)              r%d.0<1>:d    r1.2<0;1,0>:d     r%d.0<16;16,1>:w' % (pb, tb))
    emit('(W)     asr (16|M0)              r%d.0<1>:d    r%d.0<8;8,1>:d    r1.3<0;1,0>:d' % (pa, pa), '>> s, arithmetic')
    emit('(W)     asr (16|M0)              r%d.0<1>:d    r%d.0<8;8,1>:d    r1.3<0;1,0>:d' % (pb, pb))
    emit('(W)     add (16|M0)              r%d.0<1>:w    r%d.0<16;16,1>:ub  r%d.0<2;1,0>:w' % (s, Y + row, pa), 'Y + low word, columns 0-15')
    emit('(W)     add (16|M0)              r%d.0<1>:w    r%d.16<16;16,1>:ub  r%d.0<2;1,0>:w' % (s + 1, Y + row, pb), 'columns 16-31')
    if mode == '420v':  # output row = 32 bytes in one GRF
        o = OUT + row
        emit('(W)     mov (16|M0)              (sat)r%d.0<2>:ub  r%d.0<2;1,0>:w' % (o, s), 'even columns, clamp 0..255')
        emit('(W)     mov (16|M0)              (sat)r%d.1<2>:ub  r%d.1<2;1,0>:w' % (o, s), 'odd columns')
    else:  # output row = 64 bytes; lo = columns 0-15, hi = 16-31, laid out in write order
        lo = OUT + (row % 8) + (16 if row >= 8 else 0)
        hi = lo + 8
        uv = UV + row // 2
        emit('(W)     mov (16|M0)              (sat)r%d.1<2>:ub  r%d.0<16;16,1>:w' % (lo, s), 'Y0 Y1 .. of columns 0-15, clamped')
        emit('(W)     mov (16|M0)              (sat)r%d.1<2>:ub  r%d.0<16;16,1>:w' % (hi, s + 1), 'columns 16-31')
        emit('(W)     mov (16|M0)              r%d.0<2>:ub   r%d.0<16;16,1>:ub' % (lo, uv), 'Cb Cr .. from UV row %d' % (row // 2))
        emit('(W)     mov (16|M0)              r%d.0<2>:ub   r%d.16<16;16,1>:ub' % (hi, uv))

if mode == '420v':
    send(None, 2, OUT, WRITE | 2, 5, 'Y rows 0-7')
    send(None, 3, OUT + 8, WRITE | 2, 6, 'Y rows 8-15')
    send(None, 4, UV, WRITE | 3, 7, 'UV unchanged')
else:
    emit('(W)     shl (1|M0)               r7.6<1>:d     r1.0<0;1,0>:d     1:w', 'byte x of the packed row')
    emit('(W)     add (1|M0)               r7.7<1>:d     r7.6<0;1,0>:d     32:w', 'its second half')
    header(8, 'r7.6<0;1,0>:d', 'r1.1<0;1,0>:d', '0x7001F', 'rows 0-7, bytes 0-31')
    header(9, 'r7.7<0;1,0>:d', 'r1.1<0;1,0>:d', '0x7001F', 'rows 0-7, bytes 32-63')
    header(10, 'r7.6<0;1,0>:d', 'r7.0<0;1,0>:d', '0x7001F', 'rows 8-15, bytes 0-31')
    header(11, 'r7.7<0;1,0>:d', 'r7.0<0;1,0>:d', '0x7001F', 'rows 8-15, bytes 32-63')
    for i, reg in enumerate((8, 9, 10, 11)):
        send(None, reg, OUT + 8 * i, WRITE | 2, 5 + i, 'packed rows from r%d-r%d' % (OUT + 8 * i, OUT + 8 * i + 7))
emit('        sync.allrd (1|M0)                null', 'writes have read their payload', None)
emit('(W)     send.ts (8|M0)           null     r127    null    0x0    0x02000010', 'end of thread', 'EOT,@1')
open(out, 'w').write('\n'.join(lines) + '\n')
